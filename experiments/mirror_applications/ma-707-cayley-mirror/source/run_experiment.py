#!/usr/bin/env python3
"""Frozen synthetic scaled-Cayley recurrence experiment for MA-707."""
from __future__ import annotations
import argparse, csv, io, json, math, time
from pathlib import Path
import numpy as np

ROOT = Path(__file__).resolve().parents[1]
D = 4
PAIRS = ((0, 1), (0, 2), (0, 3), (1, 2), (1, 3), (2, 3))

def skew_from(c):
    a = np.zeros((D, D), dtype=np.float64)
    for v, (i, j) in zip(c, PAIRS):
        a[i, j] = v; a[j, i] = -v
    return a

def cayley(a):
    eye = np.eye(a.shape[0], dtype=np.float64)
    return np.linalg.solve(eye - a, eye + a)

def angle_code(rng, high=False):
    # The low-angle manifold uses the first two fixed shared skew generators.
    v = rng.normal(size=2)
    norm = np.linalg.norm(v) or 1.0
    v = v / norm * rng.uniform(0.035, 0.20)
    if high: v *= 4.0
    return v

def make_base(seed):
    rng = np.random.default_rng(seed)
    # A fixed shared orthogonal base, generated by QR and determinant corrected.
    q, r = np.linalg.qr(rng.normal(size=(D, D)))
    q = q @ np.diag(np.sign(np.diag(r)))
    if np.linalg.det(q) < 0: q[:, -1] *= -1
    return q

def generators(codes):
    # Fit a two-dimensional shared generator span from development task codes only.
    _, _, vt=np.linalg.svd(codes, full_matrices=True)
    span=vt[:2].T
    return [skew_from(span[:,j] * 0.5) for j in range(2)]

def mirror_matrix(base, code, gens):
    a = code[0] * gens[0] + code[1] * gens[1]
    return base @ cayley(a)

def fit_mirror(base, y, x, gens):
    # Deterministic Gauss-Newton fit in the two registered coordinates.
    code=np.zeros(2)
    for _ in range(30):
        resid=(mirror_matrix(base, code, gens) @ x.T - y.T).T.reshape(-1)
        eps=1e-5
        jac=np.column_stack([((mirror_matrix(base, code+np.eye(2)[i]*eps, gens) @ x.T - y.T).T.reshape(-1)-resid)/eps for i in range(2)])
        step=np.linalg.lstsq(jac, -resid, rcond=None)[0]
        if np.linalg.norm(step)>0.2: step*=0.2/np.linalg.norm(step)
        code += step
        if np.linalg.norm(step)<1e-10: break
    return code

def orthogonal_fit(y,x):
    u,_,vt=np.linalg.svd(y.T @ x, full_matrices=False)
    m=u@vt
    if np.linalg.det(m)<0:
        u[:,-1]*=-1; m=u@vt
    return m

def train_tasks(seed, base, low_count=6, high_count=6):
    rng=np.random.default_rng(seed); gs=[skew_from(np.eye(6)[j] * 0.5) for j in range(6)]; tasks=[]
    for high,n in ((False,low_count),(True,high_count)):
        for _ in range(n):
            code=angle_code(rng,high)
            target=mirror_matrix(base,code,gs)
            x=rng.normal(size=(128,D)); y=(target@x.T).T
            held=rng.normal(size=(32,D))
            tasks.append((high,target,x,y,held,code))
    return tasks

def rollout(m, init, steps=32):
    x=init.copy()
    for _ in range(steps): x=(m@x.T).T
    return x

def payload_bytes(arrays):
    # Canonical deterministic npz inference package, includes names/header/compression.
    bio=io.BytesIO(); np.savez(bio, **arrays); return len(bio.getvalue())

def evaluate(seed):
    t0=time.perf_counter(); base=make_base(seed+9000)
    # Four development tasks determine the shared rank-2 generator span.
    provisional=[skew_from(np.eye(6)[j] * 0.5) for j in range(6)]
    dev=train_tasks(seed+100000,base,low_count=4,high_count=0)
    dev_codes=np.stack([fit_mirror(base,y,x,provisional) for _,_,x,y,_,_ in dev])
    gs=generators(dev_codes)
    tasks=train_tasks(seed,base)
    scale=np.sqrt(np.mean(dev_codes**2,axis=0)); scale=np.where(scale<1e-12,1.0,scale)
    # Apply scalar normalization to the learned shared generators.
    gs=[g * float(np.mean(scale)) for g in gs]
    rows=[]; ops=0; fit_wall=0.
    for idx,(high,target,x,y,held,truecode) in enumerate(tasks):
        start=time.perf_counter(); code=fit_mirror(base,y,x,gs); fit_wall += time.perf_counter()-start
        methods={
            'tied_shared': base,
            'mirror_rank2_cayley': mirror_matrix(base,code,gs),
            'full_orthogonal': orthogonal_fit(y,x),
        }
        # Cheapest native low-rank additive control fit by truncated SVD of observed delta.
        delta=(y.T@x) @ np.linalg.pinv(x.T@x) - base
        u,s,vt=np.linalg.svd(delta,full_matrices=False); residual=(u[:,:2]*s[:2])@vt[:2,:]+base
        methods['shared_rank2_additive']=residual
        for name,m in methods.items():
            pred=(m@held.T).T
            err=pred-held@target.T
            # Recurrent rollout query; initial state is held-out and teacher outputs are target^32.
            p32=rollout(m,held); truth32=rollout(target,held)
            mse=float(np.mean((p32-truth32)**2))
            radius=float(np.max(np.abs(np.linalg.eigvals(m))))
            if name=='tied_shared': arrays={'shared_transition':base.astype(np.float32)}
            elif name=='mirror_rank2_cayley': arrays={'shared_transition':base.astype(np.float32),'skew_generators':np.stack(gs).astype(np.float32),'task_codes':code[None,:].astype(np.float32)}
            elif name=='full_orthogonal': arrays={'task_transition':m.astype(np.float32)}
            else: arrays={'shared_transition':base.astype(np.float32),'rank2_residual':(m-base).astype(np.float32)}
            b=payload_bytes(arrays)
            # Per-task bytes for multi-task deployment; shared base charged once amortized across tasks.
            rows.append({'condition':('high' if high else 'low')+'_'+name,'world_or_seed':seed,'method':name,'serialized_bytes':b,'train_tokens_or_examples':128,'optimizer_updates':0,'active_compute_proxy':'4x4 state transition; Cayley solve 4x4 for Mirror','wall_time_s':f'{fit_wall:.9f}','primary_metric':'32_step_rollout_mse','primary_value':f'{mse:.12g}','secondary_metric':'spectral_radius','secondary_value':f'{radius:.12g}','status_note':f'task={idx}; one_step_mse={np.mean(err**2):.6g}; fit_codes={len(tasks)}'})
    elapsed=time.perf_counter()-t0
    # Group bytes for deployment with shared terms charged once; full control stores all per-task matrices.
    n=len(tasks); mirror_total=payload_bytes({'shared_transition':base.astype(np.float32),'skew_generators':np.stack(gs).astype(np.float32),'task_codes':np.stack([fit_mirror(base,t[3],t[2],gs) for t in tasks]).astype(np.float32)})
    full_total=payload_bytes({'task_transitions':np.stack([orthogonal_fit(t[3],t[2]) for t in tasks]).astype(np.float32)})
    report={'seed':seed,'tasks':n,'low_tasks':6,'high_tasks':6,'mirror_total_bytes':mirror_total,'full_orthogonal_total_bytes':full_total,'mirror_full_ratio':mirror_total/full_total,'elapsed_wall_s':elapsed,'device':'CPU','updates':0,'fit_examples':n*128,'generator_count':2}
    return rows,report

def main():
    ap=argparse.ArgumentParser(); ap.add_argument('--seeds',nargs='+',type=int,default=[70701]); ap.add_argument('--out',default=str(ROOT/'RESULTS_CORE.csv')); ap.add_argument('--summary',default=str(ROOT/'source'/'summary.json')); args=ap.parse_args()
    rows=[]; summaries=[]
    for seed in args.seeds:
        rr,ss=evaluate(seed); rows.extend(rr); summaries.append(ss)
    with open(args.out,'w',newline='') as f:
        w=csv.DictWriter(f,fieldnames=list(rows[0])); w.writeheader(); w.writerows(rows)
    Path(args.summary).write_text(json.dumps(summaries,indent=2)+'\n')
    print(json.dumps(summaries,indent=2))
if __name__=='__main__': main()
