"""Optional POSTHOC old-checkpoint accuracy replay; NOT sealed fresh evidence.

Requires native_11,12,13.pt generated by MA-1163 baseline script.
These test labels were previously observed in older experiments; no tuning is performed.
"""
import argparse
import csv
from pathlib import Path
import sys
import torch
from torch.nn import functional as F

HERE=Path(__file__).resolve()
sys.path.insert(0,str(HERE.parents[2]/'source'))
sys.path.insert(0,str(HERE.parent))
from audit import mirror_pack,mirror_unpack,native_pack,native_unpack
from core import NativeMLP,native_flat,logits
from run import fit_teacher_weights,world_data


def main():
    p=argparse.ArgumentParser()
    p.add_argument('--checkpoint-directory',required=True)
    p.add_argument('--output',default=str(HERE.parents[1]/'results'/'legacy_teacher_replay.csv'))
    a=p.parse_args()
    torch.set_num_threads(1)
    xs,ys,idx=world_data(618201)
    labels=ys[idx['test']]
    rows=[]
    for seed in (11,12,13):
        ckpt=Path(a.checkpoint_directory)/f'native_{seed}.pt'
        net=NativeMLP().eval();net.load_state_dict(torch.load(ckpt,weights_only=True,map_location='cpu')['state'])
        original=native_flat(net)
        mirror_model,fit=fit_teacher_weights(original,'mirror',768,k=8,r=4)
        packed=mirror_pack(mirror_model.indices,mirror_model.coords,8,4)
        compressed=mirror_unpack(packed)
        native_compact=native_pack(original)
        with torch.no_grad():
            for kind,fn,nbytes in [('native_FP16',lambda:logits(native_unpack(native_compact),xs[idx['test']]),len(native_compact)),
                                   ('mirror_FP16',lambda:compressed(xs[idx['test']]),len(packed))]:
                yhat=fn()
                rows.append({'seed':seed,'kind':kind,'accuracy':float((yhat.argmax(-1)==labels).double().mean()),
                    'nll':float(F.cross_entropy(yhat,labels)),
                    'persisted_bytes':nbytes,'physical_coordinates':1210 if kind.startswith('native') else 768,
                    'split_world':'618201_REOPENED_POSTHOC','fit_uses_labels':False})
                print(rows[-1],flush=True)
    dst=Path(a.output);dst.parent.mkdir(parents=True,exist_ok=True)
    with dst.open('w',newline='') as f:
        writer=csv.DictWriter(f,fieldnames=list(rows[0]));writer.writeheader();writer.writerows(rows)

if __name__=='__main__':main()
